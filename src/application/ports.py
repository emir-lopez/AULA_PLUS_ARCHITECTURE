"""Puertos (interfaces) que la aplicación necesita. La infraestructura los implementa (DIP)."""
from __future__ import annotations

from datetime import datetime
from typing import Protocol

from domain.agenda import AgendaTutor
from domain.events import EventoDominio
from domain.sede import Sede
from domain.sesion import TransaccionSesion
from domain.value_objects import VentanaHoraria


class RepositorioTransaccionSesion(Protocol):
    def obtener(self, sesion_id: str) -> TransaccionSesion: ...
    def agregar(self, sesion: TransaccionSesion) -> None: ...
    def guardar(self, sesion: TransaccionSesion) -> None: ...
    def contar_ocupacion_sede(self, sede_id: str, ventana: VentanaHoraria) -> int: ...


class RepositorioAgendaTutor(Protocol):
    def obtener_del_tutor(self, tutor_id: str) -> AgendaTutor: ...
    def agregar(self, agenda: AgendaTutor) -> None: ...
    def guardar(self, agenda: AgendaTutor) -> None: ...


class RepositorioSede(Protocol):
    def obtener_para_reserva(self, sede_id: str) -> Sede:
        """Obtiene la sede bloqueando su fila (SELECT ... FOR UPDATE) para proteger el último cupo."""
        ...

    def agregar(self, sede: Sede) -> None: ...


class UnidadDeTrabajo(Protocol):
    transacciones: RepositorioTransaccionSesion
    agendas: RepositorioAgendaTutor
    sedes: RepositorioSede

    def __enter__(self) -> UnidadDeTrabajo: ...
    def __exit__(self, exc_type: object, exc: object, tb: object) -> None: ...
    def confirmar(self) -> None: ...
    def revertir(self) -> None: ...


class Reloj(Protocol):
    def ahora(self) -> datetime: ...


class LecturasAulaPlus(Protocol):
    """Lado de lectura (CQRS): devuelve diccionarios/DTOs, nunca Aggregates."""

    def detalle_sesion(self, sesion_id: str) -> dict: ...
    def tutores_disponibles(self, ventana: VentanaHoraria, ahora: datetime, dias_vigencia: int) -> list[dict]: ...
    def pagos_listos_para_liberar(self, ahora: datetime, horas_retencion: int) -> list[str]: ...
    def disputas_pendientes(self) -> list[dict]: ...
    def eventos(self, agregado_id: str | None = None) -> list[EventoDominio]: ...
    def indicadores(self) -> dict: ...
